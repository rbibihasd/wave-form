export function findCountryConfig(countryName: string): FormCountryConfig | undefined {
  if (!countryName) return undefined;
  const target = countryName.trim().toLowerCase();
  return WORLD_COUNTRIES_AND_CITIES.find(
    (c) => c.country.toLowerCase() === target || c.code.toLowerCase() === target
  );
}

export function findCityConfig(countryName: string, cityName: string): FormCityConfig | undefined {
  const country = findCountryConfig(countryName);
  if (!country) return undefined;
  const target = cityName.trim().toLowerCase();
  return country.cities.find(
    (city) => city.name.toLowerCase() === target || city.region.toLowerCase().includes(target)
  );
}
